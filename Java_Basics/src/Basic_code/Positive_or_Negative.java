import java.util.Scanner;



public class Positive_or_Negative {
	
public static void main(String[] args) {
	
	Scanner sc = new Scanner(System.in);
	 int num = sc.nextInt();
	 
	 if(num>0) {
		 System.out.println("It is positive");
	 }else {
		 System.out.println("IT is negative");
	 }
}
	
	

}
